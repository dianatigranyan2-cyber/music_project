// Isolated PostgreSQL. This test never connects to the real Supabase project.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require = createRequire(new URL('../.music-import/db-check/package.json', import.meta.url));
const {PGlite} = require('@electric-sql/pglite');
const db = new PGlite();
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const [diana, other] = [id(1), id(2)];
const native = {title: 'Native song', artist: 'Original artist', album: '', genre: 'Поп', duration_seconds: 180, audio_path: id(10) + '.mp3', audio_sha256: 'a'.repeat(64), audio_bytes: 10000, source_url: 'https://example.org/track', license_code: 'CC-BY-4.0', license_url: 'https://creativecommons.org/licenses/by/4.0/', attribution: 'Original artist — Native song. CC BY 4.0.', is_published: true};
const imported = {title: 'Imported song', artist: 'Actual performer', album: '', genre: 'Поп', duration_seconds: 180, external_id: 'G0wyE', source_url: 'https://audius.co/uploader/song', attribution: 'Actual performer. Played via Audius API under Audius OML.', is_published: true, external_cover_url: null, external_metadata: {account: {name: 'Uploader'}, license: 'All rights reserved'}};
const role = async (name, user = '') => db.exec(`reset role; set role ${name}; set request.jwt.claim.sub='${user}';`);
const save = async data => (await db.query('select catalog_save_audius($1::jsonb) as result', [JSON.stringify(data)])).rows[0].result;
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth,public to anon,authenticated;
    create table public.profiles(id uuid primary key, username text);
    insert into auth.users values('${diana}'),('${other}');
    insert into public.profiles values('${diana}','UserZero_Diana'),('${other}','other');
    create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(bucket_id text,name text); alter table storage.objects enable row level security;
    grant usage on schema storage to anon,authenticated; grant all on storage.objects to anon,authenticated;
    create table public.stories(id uuid primary key default gen_random_uuid(),music_track_id uuid);`);
  for (const file of ['music_library.sql', 'music_library_licenses.sql', 'catalog_admin.sql', 'personal_music.sql']) await db.exec(await readFile(new URL('../supabase/' + file, import.meta.url), 'utf8'));
  await role('authenticated', diana);
  const nativeId = (await db.query('select catalog_save_track($1::jsonb) as id', [JSON.stringify(native)])).rows[0].id;
  await db.exec('reset role;');
  const migration = await readFile(new URL('../supabase/audius_catalog.sql', import.meta.url), 'utf8');
  await db.exec(migration); await db.exec(migration);
  assert.equal((await db.query('select provider from music_tracks where id=$1', [nativeId])).rows[0].provider, 'storage');
  for (const [name, user] of [['anon', ''], ['authenticated', other]]) {
    await role(name, user);
    await assert.rejects(save(imported), error => error.code === '42501');
  }
  await role('authenticated', diana);
  const first = await save(imported);
  assert.equal(first.alreadyImported, false); assert.equal(first.isPublished, true);
  const duplicate = await save({...imported, artist: 'Wrong replacement', title: 'Wrong replacement'});
  assert.equal(duplicate.id, first.id); assert.equal(duplicate.alreadyImported, true);
  const row = (await db.query('select * from music_tracks where id=$1', [first.id])).rows[0];
  assert.equal(row.title, imported.title); assert.equal(row.provider, 'audius'); assert.equal(row.audio_path, null);
  assert.equal(row.audio_sha256, null); assert.equal(row.audio_bytes, null); assert.equal(row.license_code, 'Audius-OML');
  assert.equal((await db.query('select name from music_artists where id=$1', [row.artist_id])).rows[0].name, 'Actual performer');
  assert.equal(row.external_metadata.account.name, 'Uploader');
  await assert.rejects(db.query("update music_tracks set audio_path=$1 where id=$2", [id(12) + '.mp3', first.id]), error => error.code === '23514');
  await assert.rejects(db.query("update music_tracks set audio_path=null where id=$1", [nativeId]), error => error.code === '23514');
  await assert.rejects(db.query("update music_tracks set license_code='CC-BY-4.0' where id=$1", [first.id]), error => error.code === '23514');
  await assert.rejects(db.query("update music_tracks set license_url='https://example.org/wrong' where id=$1", [nativeId]), error => error.code === '23514');
  await assert.rejects(save({...imported, id: nativeId}), /не найден/);
  await save({...imported, id: first.id, is_published: false});
  await role('anon');
  assert.equal((await db.query('select id from music_tracks where id=$1', [first.id])).rows.length, 0);
  await role('authenticated', other);
  await assert.rejects(db.query('insert into music_favorites(user_id,track_id) values($1,$2)', [other, first.id]));
  await role('authenticated', diana);
  await save({...imported, id: first.id, title: 'Edited song', is_published: true});
  await role('authenticated', other);
  await db.query('insert into music_favorites(user_id,track_id) values($1,$2)', [other, first.id]);
  const playlist = (await db.query("insert into music_playlists(user_id,title,description) values($1,'Test playlist','') returning id", [other])).rows[0].id;
  await db.query('select music_playlist_add_track($1,$2)', [playlist, first.id]);
  assert.equal((await db.query('select track_id from music_playlist_tracks where playlist_id=$1', [playlist])).rows[0].track_id, first.id);
  await db.exec('reset role;');
  await assert.rejects(db.query('insert into stories(music_track_id) values($1)', [first.id]), /пока доступна для прослушивания/);
  await db.query('insert into stories(music_track_id) values($1)', [nativeId]);
  assert.equal((await db.query('select count(*)::int as n from music_tracks')).rows[0].n, 2);
  console.log('PASS: repeatable Audius migration; native tracks preserved; admin-only import/edit; idempotent import; provider/ licence constraints; hidden tracks; favorites/playlists; story restriction.');
} finally {await db.close();}
